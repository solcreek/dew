#!/usr/bin/env python3
"""Generate rust/dew-agent/src/confine/syscalls.rs from go-seccomp-bpf.

The Rust agent must resolve SystemCallFilter= names exactly as the Go agent
does, so it uses the same tables: the syscall name -> number maps that
go-seccomp-bpf ships in arch/zsyscalls.go, for the two guest arches.

Usage (from the repo root):
    python3 scripts/gen-seccomp-syscalls.py "$(go env GOMODCACHE)/github.com/elastic/go-seccomp-bpf@<version>/arch/zsyscalls.go"
"""

import re
import sys

ARCHES = [("syscallsAARCH64", "AARCH64"), ("syscallsX86_64", "X86_64")]
OUT = "rust/dew-agent/src/confine/syscalls.rs"


def parse(src, var):
    m = re.search(r"var %s = map\[int\]string\{\n(.*?)\n\}" % re.escape(var), src, re.S)
    if not m:
        sys.exit("map %s not found" % var)
    table = {}
    for line in m.group(1).splitlines():
        e = re.fullmatch(r'\s*(\d+):\s*"([a-z0-9_]+)",', line)
        if not e:
            sys.exit("unexpected line in %s: %r" % (var, line))
        num, name = int(e.group(1)), e.group(2)
        if name in table:
            sys.exit("duplicate name %s in %s" % (name, var))
        table[name] = num
    return table


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    path = sys.argv[1]
    src = open(path).read()
    version = re.search(r"go-seccomp-bpf@(v[0-9.]+)", path)
    out = [
        "// @generated by scripts/gen-seccomp-syscalls.py from go-seccomp-bpf %s" % (version.group(1) if version else "(unknown version)"),
        "// arch/zsyscalls.go. Do not edit by hand; regenerate instead.",
        "//",
        "// Syscall name -> number for each guest arch, sorted by name, identical to",
        "// the tables the Go agent's SystemCallFilter= resolution uses.",
        "",
    ]
    for var, const in ARCHES:
        table = parse(src, var)
        out.append("pub const %s: &[(&str, u32)] = &[" % const)
        for name in sorted(table):
            out.append('    ("%s", %d),' % (name, table[name]))
        out.append("];")
        out.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(out))
    print("wrote %s" % OUT)


if __name__ == "__main__":
    main()
